// Runs every query in the SQL course on the practice database and writes src/content/sql/results.ts,
// the result tables shown on the lesson pages. src/lib/sql.test.ts re-runs them and fails if anything drifts.
// Run: npm run docs (or: npx vitest run --config vitest.docs.config.ts scripts/sql-results.gen.ts)
import { writeFileSync } from 'node:fs'
import { it } from 'vitest'
import initSqlJs from 'sql.js'
import { plantSql } from '../src/content/sql/plant'
import { SQL_LESSONS } from '../src/content/sql/course'

it('writes the SQL course result tables', async () => {
  const SQL = await initSqlJs()
  const run = (sql: string) => {
    const db = new SQL.Database(); db.run(plantSql())
    try { const r = db.exec(sql); const last = r[r.length - 1]; return last ? { columns: last.columns, rows: last.values } : { columns: [], rows: [] } }
    catch (e) { return { error: (e as Error).message } }
    finally { db.close() }
  }
  const out: Record<string, unknown> = {}
  for (const l of SQL_LESSONS) {
    for (const e of l.examples) out[e.id] = run(e.sql)
    for (const m of l.mistakes) { out[`${m.id}:wrong`] = run(m.wrong); out[`${m.id}:fix`] = run(m.fix) }
    for (const t of l.tasks) out[t.id] = run(t.solution)
  }
  writeFileSync('src/content/sql/results.ts', `// Generated by scripts/sql-results.gen.ts from the SQL course and the practice database. Do not edit by hand.\nimport type { Cell } from '../../lib/sql'\nexport type Stored = { columns: string[]; rows: Cell[][] } | { error: string }\nexport const RESULTS: Record<string, Stored> = ${JSON.stringify(out, null, 0).replace(/\},"/g, '},\n"')}\n`)
})
