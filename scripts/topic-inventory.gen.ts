// Run npm run docs to regenerate the full topic inventory from the live lesson registry.
import { writeFileSync } from 'node:fs'
import { expect, it } from 'vitest'
import { CONCEPTS } from '../src/content/full'
import { PILOTS, studioCitations } from '../src/content/topicStudio'
import { hasVisual } from '../src/lib/contentStats'
import { ALGOS } from '../src/content/algos'

it('generates a per-topic intelligence studio inventory',()=>{
  const fields = ['Overview','Analogy','Objectives','Visual/lab','Algorithm','Example','Checked example','Citations','Assumptions','Assessment content','Application','Interview','Dedicated pilot']
  const escape = (s:string) => s.replace(/\|/g,'\\|').replace(/\n/g,' ')
  const lines = ['# Topic Intelligence Studio — per-topic inventory','','Generated by npm run docs. Presence is not proof of quality, human review, or a passing build. Every existing lesson has a shared overview and navigation; this inventory measures the underlying authored content.','','| Topic ID | Topic | '+fields.join(' | ')+' | Missing authored fields |','| --- | --- | '+fields.map(()=> '---').join(' | ')+' | --- |']
  const yn = (v:boolean)=>v?'yes':'—'
  const rows=CONCEPTS.map(c=>{
    const p=PILOTS[c.id]
    const values=[!!c.one,!!(c.analogy||p?.mental),!!c.objectives?.length,hasVisual(c)||!!p,!!ALGOS[c.id]||p?.kind==='newton',!!(c.example||p?.example),!!c.example?.check,!!studioCitations(c).length,!!(c.assumptions?.length||p?.limit),!!(p?.practice||c.example||c.iq?.length),!!(c.real||c.used||p?.example),!!c.iq?.length,!!p]
    return '| '+[c.id,escape(c.term),...values.map(yn),fields.filter((_,i)=>!values[i]).join(', ')||'None listed'].join(' | ')+' |'
  })
  expect(rows.length).toBe(CONCEPTS.length)
  writeFileSync('docs/TOPIC-INVENTORY.md',[...lines,...rows,''].join('\n'))
})
