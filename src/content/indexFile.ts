import type { Concept } from '../types'
import { toIndex } from './assemble'

/** The exact text of src/content/conceptIndex.generated.ts for a lesson list. */
export function renderIndex(list: Concept[]) {
  const rows = list.map((c) => '  ' + JSON.stringify(toIndex(c)) + ',').join('\n')
  return `// Generated by scripts/concept-index.gen.ts (\`npm run docs\`) from src/content/full.ts. Do not edit by hand.
import type { ConceptIndex } from './assemble'

export const INDEX: ConceptIndex[] = [
${rows}
]
`
}
