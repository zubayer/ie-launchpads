// Regenerates docs/CURRICULUM-GAP-ANALYSIS.md from src/content/curriculum.ts and the concept library.
// Run: npm run docs:gaps
import { writeFileSync } from 'node:fs'
import { it } from 'vitest'
import { coverage } from '../src/lib/coverage'
import { CONCEPTS } from '../src/content'

it('writes the curriculum gap analysis', () => {
  const rows = coverage()
  const total = rows.reduce((n, a) => n + a.area.topics.length, 0)
  const done = rows.reduce((n, a) => n + a.covered.length, 0)
  const out: string[] = [
    '# Curriculum gap analysis',
    '',
    `Generated by \`npm run docs:gaps\` from \`src/content/curriculum.ts\` (the V2 blueprint topic lists) and the ${CONCEPTS.length}-concept library. Do not edit by hand.`,
    '',
    `**${done} of ${total} blueprint topics (${Math.round((100 * done) / total)}%) have a lesson.** "Covered" means a lesson exists; it does not mean the lesson is complete or reviewed. Matches come from exact names and aliases plus a reviewed override table (\`TOPIC_MAP\`).`,
    '',
    '| Area | Knowledge area | Covered | Level | Missing topics |',
    '|---|---|---|---|---|',
    ...rows.map((a) => `| ${a.area.code} | ${a.area.name} | ${a.covered.length}/${a.area.topics.length} | ${a.level} | ${a.missing.join(', ') || '—'} |`),
    '',
    '## Priorities',
    '',
    'Areas at None/Low coverage need new lessons before deeper enrichment: ' + rows.filter((a) => a.level === 'None' || a.level === 'Low').map((a) => `${a.code} ${a.area.name}`).join('; ') + '.',
    '',
    'Avoid duplicates: several blueprint topics appear in more than one area (ANOVA, predictive maintenance, digital twin, sensitivity analysis, forecasting). Each is taught once and linked from every area that needs it.',
    '',
  ]
  writeFileSync('docs/CURRICULUM-GAP-ANALYSIS.md', out.join('\n'))
})
