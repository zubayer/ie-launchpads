// Regenerates docs/CONTENT-COVERAGE.md from the live content. Run: npm run docs:coverage
import { readFileSync, writeFileSync } from 'node:fs'
import { it } from 'vitest'
import { CONCEPTS } from '../src/content'
import { DOMAINS } from '../src/content/domains'
import { ROLES } from '../src/content/roles'
import { ELEMENTS } from '../src/content/periodic'
import { CHAINS } from '../src/content/chains'
import { GUIDE, PAIRS, MYSTERIES, TOOLS, HOTSPOTS } from '../src/content/discovery'
import { SOURCES } from '../src/content/sources'
import { MODES } from '../src/lib/modes'
import { SIM_META } from '../src/sims/registry'
import { coverage } from '../src/lib/coverage'
import { domainCoverage, fieldCoverage, formulaWithoutSymbols, isUncheckedNumeric, meetsMinimum, pct, reviewCounts } from '../src/lib/contentStats'
import { EQUATIONS } from '../src/content/equations'
import { PATHWAYS } from '../src/content/pathways'

it('writes the content coverage dashboard', () => {
  const app = readFileSync('src/App.tsx', 'utf8')
  const routes = [...app.matchAll(/<Route (?:index|path="([^"]+)")/g)].map((m) => m[1] ?? '(index)').filter((p) => p !== '*')
  const rows = coverage()
  const bpTotal = rows.reduce((n, a) => n + a.area.topics.length, 0)
  const bpDone = rows.reduce((n, a) => n + a.covered.length, 0)
  const n = CONCEPTS.length
  const min = CONCEPTS.filter(meetsMinimum).length
  const unchecked = CONCEPTS.filter(isUncheckedNumeric)
  const noSyms = CONCEPTS.filter(formulaWithoutSymbols)
  const rev = reviewCounts()
  const doms = domainCoverage()
  const f = fieldCoverage()
  const cell = (k: string, d: (typeof doms)[number]) => { const x = d.fields.find((y) => y.key === k)!; return `${pct(x.n, x.of)}%` }
  const out = [
    '# Content coverage',
    '',
    'Generated by `npm run docs:coverage` from the content in `src/`. Do not edit by hand. A field counts as present when the lesson data has it; presence is not proof of quality or review.',
    '',
    '## Inventory',
    '',
    '| Item | Count |',
    '|---|---|',
    `| Concepts (lessons) | ${n} |`,
    `| Domains | ${DOMAINS.length} |`,
    `| Simulators and labs (\`/lab/:id\`) | ${SIM_META.length} |`,
    `| Role paths | ${ROLES.length} |`,
    `| Periodic-table methods | ${ELEMENTS.length} |`,
    `| Reaction chains | ${CHAINS.length} |`,
    `| Learning modes | ${MODES.length} |`,
    `| Formulas in the library | ${CONCEPTS.filter((c) => c.formula).length} |`,
    `| Equation Explorer experiments | ${EQUATIONS.length} |`,
    `| Guided pathways | ${PATHWAYS.length} |`,
    `| Field-guide nodes / confused pairs / mysteries / tool cards / waste hotspots | ${Object.keys(GUIDE).length} / ${PAIRS.length} / ${MYSTERIES.length} / ${TOOLS.length} / ${HOTSPOTS.length} |`,
    `| Registered sources | ${Object.keys(SOURCES).length} |`,
    `| App routes (excluding not-found) | ${routes.length} |`,
    `| Curriculum blueprint topics with a lesson | ${bpDone} of ${bpTotal} (${pct(bpDone, bpTotal)}%) |`,
    '',
    '## Lesson fields (all domains)',
    '',
    '| Field | Lessons | Share |',
    '|---|---|---|',
    ...f.map((x) => `| ${x.label} | ${x.n} of ${x.of} | ${pct(x.n, x.of)}% |`),
    `| **Meets the V3 core minimum** (something to see or do, a mistake, an application, a self-check, a source) | **${min} of ${n}** | **${pct(min, n)}%** |`,
    '',
    '## By domain',
    '',
    '| Domain | Lessons | Meets minimum | Why | Example | Visual or lab | Mistakes | Interview | Sources |',
    '|---|---|---|---|---|---|---|---|---|',
    ...doms.map((d) => `| ${d.name} | ${d.n} | ${d.min} (${pct(d.min, d.n)}%) | ${cell('why', d)} | ${cell('example', d)} | ${cell('visual', d)} | ${cell('mistakes', d)} | ${cell('iq', d)} | ${cell('cites', d)} |`),
    '',
    '## Review status',
    '',
    'Statuses follow AGENTS.md. None of them is expert review: no named human expert has reviewed any lesson yet.',
    '',
    '| Status | Lessons |',
    '|---|---|',
    ...Object.entries(rev).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k === 'none' ? 'No review record' : k} | ${v} |`),
    '',
    '## Numerical QA',
    '',
    `- Worked examples: ${CONCEPTS.filter((c) => c.example).length}; machine-checked by \`npm test\`: ${CONCEPTS.filter((c) => c.example?.check).length}. Each check's value must also appear in the displayed answer (\`src/lib/numeric-qa.test.ts\`).`,
    `- Examples with a number in the answer but no machine check: ${unchecked.length}${unchecked.length ? ` (${unchecked.map((c) => '`' + c.id + '`').join(', ')})` : ''}. The test suite fails if this count rises.`,
    `- Formulas without symbol definitions: ${noSyms.length} of ${CONCEPTS.filter((c) => c.formula).length}. Equation Explorer experiments carry full symbols, units and bounds.`,
    '',
  ]
  writeFileSync('docs/CONTENT-COVERAGE.md', out.join('\n'))
})
