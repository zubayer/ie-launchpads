/** Only identify an acronym when an explicit name is paired with one unambiguous short label.
 * Mixed labels are retained as existing terminology, never split or guessed automatically. */
const short = (s:string) => /^[A-Z][A-Z0-9&/.-]{1,11}$/.test(s)
export function metadataTerm(c: Concept): TermDetail | undefined {
  if(!c.full || c.full===c.term) return
  if(short(c.full) && !short(c.term)) return {label:c.full,meaning:c.term,kind:'acronym'}
  if(short(c.term) && !short(c.full)) return {label:c.term,meaning:c.full,kind:'acronym'}
  return {label:c.term,meaning:c.full,kind:'term'}
}
