import { writeFileSync } from 'node:fs'
import { it, expect } from 'vitest'
import { CONCEPTS } from '../src/content'
import { hasVisual } from '../src/lib/contentStats'
it('audits the educational and career content of every topic', () => {
  const rows = CONCEPTS.map(c => {
    const fields = [!!c.analogy, !!c.why, !!c.objectives?.length, hasVisual(c), !!c.formula, !!c.example?.check, !!c.real, !!c.assumptions?.length, !!c.cites?.length, !!c.rel?.length, (c.iq?.length || 0)>=2]
    const labels=['analogy','purpose','objectives','visual/lab','formula (if applicable)','checked example (if applicable)','application','limitations','citation','connections','two interview questions']
    const missing=labels.filter((_,i)=>!fields[i])
    return '| '+c.id+' | '+(c.iq?.length || 0)+' | '+(c.iq?.filter(q=>q.type==='case').length || 0)+' | '+missing.join(', ')+' |'
  })
  expect(rows.length).toBe(CONCEPTS.length)
  writeFileSync('docs/CAREER-DEPTH-INVENTORY.md',['# Curriculum depth and career audit','','Generated by npm run docs; missing fields are review candidates, not mandatory for every topic. Presence does not prove accuracy, verified interviews or mastery.','','| Topic | Interview Qs | Case Qs | Missing fields |','| --- | ---: | ---: | --- |',...rows,''].join('\n'))
})
